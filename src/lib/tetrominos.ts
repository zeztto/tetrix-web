export function getTetrominoShape(type: TetrominoType, rotation: RotationState): Shape {
  return SHAPES[type][rotation];
}

export function getTetrominoColor(type: TetrominoType): string {
  return COLORS[type];
}

export function getWallKickOffsets(
  type: TetrominoType,
  fromRotation: RotationState,
  toRotation: RotationState
): Position[] {
  if (type === 'O') {
    return [];
  }

  const key = `${fromRotation}->${toRotation}`;
  const data = type === 'I' ? WALL_KICK_DATA_I : WALL_KICK_DATA_JLSTZ;

  return data[key] || [];
}
